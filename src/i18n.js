var currentLang = 'fr';
var listeners = [];

function interpolate(str, params) {
  if (!params) return str;
  var result = str;
  for (var key in params) {
    if (params.hasOwnProperty(key)) {
      result = result.split('{' + key + '}').join(String(params[key]));
    }
  }
  return result;
}

export function t(key, params) {
  var dict = currentLang === 'en' ? EN : FR;
  var val = dict[key];
  if (val === undefined) {
    val = FR[key];
    if (val === undefined) return key;
  }
  return interpolate(val, params);
}

export function getLang() { return currentLang; }

export function setLang(lang) {
  if (lang !== 'fr' && lang !== 'en') return;
  currentLang = lang;
  try { AsyncStorage.setItem('@myhostkit_lang', lang); } catch(e) {}
  listeners.forEach(function(fn) { try { fn(lang); } catch(e) {} });
}

export function initLang() {
  return AsyncStorage.getItem('@myhostkit_lang').then(function(saved) {
    if (saved === 'fr' || saved === 'en') { currentLang = saved; }
    return currentLang;
  }).catch(function() { return currentLang; });
}

export function onLangChange(fn) {
  listeners.push(fn);
  return function() {
    var idx = listeners.indexOf(fn);
    if (idx >= 0) listeners.splice(idx, 1);
  };
}

export function useLang() {
  var state = useState(currentLang);
  var lang = state[0];
  var setLangState = state[1];
  useEffect(function() {
    var unsub = onLangChange(function(l) { setLangState(l); });
    return unsub;
  }, []);
  return lang;
}
